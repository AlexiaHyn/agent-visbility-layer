import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { ProjectService } from '../project-service.mjs';
import { createSectionExtension, PLANNING_TOOLS, IMPLEMENTATION_TOOLS } from '../section-extension.mjs';
const definition = (id, parentId, kind) => ({ id, parentId, kind, category: 'implement', title: id, objective: 'Create a function', requirementIds: ['R1'], dependsOn: [], inputs: [], outputs: ['function'], acceptanceCriteria: ['Function works'], validation: ['Run tests'] });
async function setup(t) {
  const workspace = await mkdtemp(join(tmpdir(), 'pi-project-protocol-')); t.after(() => rm(workspace, { recursive: true, force: true }));
  const service = new ProjectService(join(workspace, 'data')), project = await service.create({ title: 'Project', workspace });
  const tools = new Map(), events = new Map(); let activeTools;
  createSectionExtension({ service, projectId: project.id })({ registerTool: tool => tools.set(tool.name, tool), on: (name, handler) => events.set(name, handler), setActiveTools: names => { activeTools = names; } });
  const ctx = { sessionManager: { getLeafId: () => 'entry-before' } };
  const execute = (name, args) => tools.get(name).execute('protocol-call', args, undefined, undefined, ctx);
  const submit = () => execute('submit_plan', { reason: 'Initial plan', specification: { description: 'Create a function', requirements: [{ id: 'R1', text: 'Working function' }], acceptanceCriteria: ['Function works'] }, sections: [definition('S1', project.id, 'step')] });
  return { workspace, service, project, execute, submit, events, active: () => activeTools };
}
test('planning enables read-only tools and blocks implementation until user approval', async t => {
  const { project, service, events, submit, active } = await setup(t);
  await events.get('before_agent_start')({ systemPromptOptions: { sections: {} } });
  assert.deepEqual(active(), PLANNING_TOOLS);
  assert.equal((await events.get('tool_call')({ toolName: 'write', toolCallId: 'mutation', input: {} })).block, true);
  await submit();
  assert.equal((await service.store.get(project.id)).approvedPlanRevision, 0);
  assert.equal((await events.get('tool_call')({ toolName: 'start_work_unit', input: {} })).block, true);
  await service.event(project.id, 'plan_approved', { planRevision: 1 });
  await events.get('before_agent_start')({ systemPromptOptions: { sections: {} } });
  assert.deepEqual(active(), IMPLEMENTATION_TOOLS);
});
test('declared work units own actual calls, capture checkpoints and enforce completion evidence', async t => {
  const { workspace, service, project, events, submit, execute } = await setup(t);
  await submit(); await service.event(project.id, 'plan_approved', { planRevision: 1 });
  assert.equal((await events.get('tool_call')({ toolName: 'edit', toolCallId: 'unassigned', input: {} })).block, true);
  await execute('declare_sections', { sections: [definition('W1', 'S1', 'work_unit')] });
  await execute('start_work_unit', { sectionId: 'W1' });
  await assert.rejects(execute('finish_work_unit', { status: 'completed', summary: 'No work', validation: [] }), /at least one/);
  assert.equal(await events.get('tool_call')({ toolName: 'write', toolCallId: 'write-1', input: { path: 'hello.js' } }), undefined);
  await writeFile(join(workspace, 'hello.js'), 'export const hello = () => 1;');
  await events.get('tool_result')({ toolCallId: 'write-1', content: [{ type: 'text', text: 'Written' }], isError: false });
  await execute('finish_work_unit', { status: 'completed', summary: 'Function added', validation: [{ criterion: 'Function works', met: true, evidence: 'Focused check passed' }] });
  const state = await service.store.get(project.id);
  assert.equal(state.attempts[0].actions[0].id, 'write-1');
  assert.equal(state.attempts[0].status, 'completed');
  assert.ok(state.attempts[0].beforeCheckpointId && state.attempts[0].afterCheckpointId);
  const preview = await service.impact(project.id, 'W1');
  assert.equal(preview.checkpointPreview.changes[0].path, 'hello.js');
  assert.equal(await readFile(join(workspace, 'hello.js'), 'utf8'), 'export const hello = () => 1;');
});
test('confirmed edits permit read-only impact review but never immediate implementation', async t => {
  const { workspace, service, project, events, submit, execute } = await setup(t);
  await submit(); await service.event(project.id, 'plan_approved', { planRevision: 1 });
  await execute('declare_sections', { sections: [definition('W1', 'S1', 'work_unit')] });
  await writeFile(join(workspace, 'existing.js'), 'original code');
  await service.event(project.id, 'draft_saved', { basePlanRevision: 1, operations: [{ kind: 'remove', sectionId: 'W1' }], notes: 'Remove this feature and repair references.' });
  await service.event(project.id, 'draft_confirmed', {});
  assert.equal((await events.get('tool_call')({ toolName: 'write', toolCallId: 'blocked-change', input: {} })).block, true);
  assert.equal(await events.get('tool_call')({ toolName: 'read', toolCallId: 'review-read', input: { path: 'existing.js' } }), undefined);
  await events.get('tool_result')({ toolCallId: 'review-read', content: [], isError: false });
  assert.equal(await readFile(join(workspace, 'existing.js'), 'utf8'), 'original code');
  const spec = { description: 'Remove the feature safely', requirements: [{ id: 'R1', text: 'Feature removed without stale references' }], acceptanceCriteria: ['Feature removed safely'] };
  const sections = [definition('S1', project.id, 'step'), definition('W2', 'S1', 'work_unit')];
  await assert.rejects(service.submitPlan(project.id, { specification: spec, sections }, 'Cleanup'), /change-impact review/);
  await service.submitPlan(project.id, { specification: spec, sections }, 'Minimal cleanup', { summary: 'Remove the feature and reuse existing imports.', changes: [{ sectionId: 'W1', operation: 'remove', reason: 'User requested removal', reuseStrategy: 'Reuse the existing shared handler' }], validation: ['Check stale references and run tests'] });
  const proposed = await service.store.get(project.id);
  assert.equal(proposed.planRevision, 2); assert.equal(proposed.approvedPlanRevision, 0);
  assert.equal((await events.get('tool_call')({ toolName: 'edit', toolCallId: 'still-blocked', input: {} })).block, true);
  await service.event(project.id, 'plan_approved', { planRevision: 2 });
  assert.equal((await service.store.get(project.id)).draft, null);
});
